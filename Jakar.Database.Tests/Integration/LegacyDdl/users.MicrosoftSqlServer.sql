CREATE TABLE users (
    is_active                 bit                           NOT NULL,
    is_disabled               bit                           NOT NULL,
    is_email_confirmed        bit                           NOT NULL,
    is_locked                 bit                           NOT NULL,
    is_phone_number_confirmed bit                           NOT NULL,
    is_two_factor_enabled     bit                           NOT NULL,
    bad_logins                int                           NULL,
    escalate_to               uniqueidentifier              NULL,
    id                        uniqueidentifier              DEFAULT NEWID() PRIMARY KEY,
    image_id                  uniqueidentifier              NULL,
    session_id                uniqueidentifier              NULL,
    subscription_id           uniqueidentifier              NULL,
    user_id                   uniqueidentifier              NOT NULL,
    date_created              datetimeoffset                NOT NULL,
    last_bad_attempt          datetimeoffset                NULL,
    last_login                datetimeoffset                NULL,
    last_modified             datetimeoffset                NULL,
    lock_date                 datetimeoffset                NULL,
    lockout_end               datetimeoffset                NULL,
    refresh_token_expiry_time datetimeoffset                NULL,
    subscription_expires      datetimeoffset                NULL,
    preferred_language        nvarchar(11)                  NOT NULL,
    authenticator_key         nvarchar(max)                 NULL,
    company                   nvarchar(max)                 NULL,
    concurrency_stamp         nvarchar(max)                 NULL,
    department                nvarchar(max)                 NULL,
    description               nvarchar(max)                 NULL,
    email                     nvarchar(450)                 NULL,
    ext                       nvarchar(max)                 NULL,
    first_name                nvarchar(450)                 NULL,
    full_name                 nvarchar(450)                 NULL,
    gender                    nvarchar(max)                 NULL,
    last_name                 nvarchar(450)                 NULL,
    password_hash             nvarchar(max)                 NULL,
    phone_number              nvarchar(450)                 NULL,
    refresh_token_hash        nvarchar(max)                 NULL,
    security_stamp            nvarchar(max)                 NULL,
    title                     nvarchar(max)                 NULL,
    user_name                 nvarchar(max)                 NOT NULL,
    website                   nvarchar(max)                 NULL,
    rights                    nvarchar(max)                 NOT NULL,
    additional_data           nvarchar(max)                 NULL,

    FOREIGN KEY (image_id) REFERENCES files(id)
);