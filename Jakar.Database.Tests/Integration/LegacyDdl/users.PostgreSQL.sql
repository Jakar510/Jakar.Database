CREATE TABLE users (
    is_active                 bool                          NOT NULL,
    is_disabled               bool                          NOT NULL,
    is_email_confirmed        bool                          NOT NULL,
    is_locked                 bool                          NOT NULL,
    is_phone_number_confirmed bool                          NOT NULL,
    is_two_factor_enabled     bool                          NOT NULL,
    bad_logins                integer                       NULL,
    escalate_to               uuid                          NULL,
    id                        uuid                          DEFAULT gen_random_uuid() PRIMARY KEY,
    image_id                  uuid                          NULL,
    session_id                uuid                          NULL,
    subscription_id           uuid                          NULL,
    user_id                   uuid                          NOT NULL,
    date_created              timestamptz                   NOT NULL,
    last_bad_attempt          timestamptz                   NULL,
    last_login                timestamptz                   NULL,
    last_modified             timestamptz                   NULL,
    lock_date                 timestamptz                   NULL,
    lockout_end               timestamptz                   NULL,
    refresh_token_expiry_time timestamptz                   NULL,
    subscription_expires      timestamptz                   NULL,
    preferred_language        varchar(11)                   NOT NULL,
    authenticator_key         text                          NULL,
    company                   text                          NULL,
    concurrency_stamp         text                          NULL,
    department                text                          NULL,
    description               text                          NULL,
    email                     text                          NULL,
    ext                       text                          NULL,
    first_name                text                          NULL,
    full_name                 text                          NULL,
    gender                    text                          NULL,
    last_name                 text                          NULL,
    password_hash             text                          NULL,
    phone_number              text                          NULL,
    refresh_token_hash        text                          NULL,
    security_stamp            text                          NULL,
    title                     text                          NULL,
    user_name                 text                          NOT NULL,
    website                   text                          NULL,
    rights                    text                          NOT NULL,
    additional_data           json                          NULL,

    FOREIGN KEY (image_id) REFERENCES files(id)
);