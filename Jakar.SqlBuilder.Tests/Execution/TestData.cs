using System;
using System.Collections.Generic;
using Jakar.SqlBuilder;



namespace Jakar.SqlBuilder.Tests.Execution;


/// <summary>
///     The schema and rows every engine is seeded with. Identifiers go through the builder's own quoting, so a dialect's DDL names its tables the way its SQL refers to them.
///     <code>
///     users:  1 Ada     ada@x.io  active 36 | 2 Bob   NULL   inactive 17 | 3 Cy  cy@x.io active 65 | 4 O'Brien ob@x.io active 40
///     orders: 1 user 1 'a' 10 | 2 user 1 'b' 20 | 3 user 3 'c' 5 | 4 user 99 'd' 7   (user 99 doesn't exist: for RIGHT / FULL joins)
///     </code>
///     <see cref="User"/> and <see cref="Order"/> map the same tables for the typed overloads.
/// </summary>
public static class TestData
{
    public static IEnumerable<string> Schema( SqlDialectKind dialect )
    {
        ( string identity, string text, string integer, string boolean ) = Types(dialect);
        string terminator = dialect.SupportsStatementTerminator()
                                ? ";"
                                : string.Empty;

        yield return $"CREATE TABLE {Q(dialect, "users")} ({Q(dialect, "id")} {identity}, {Q(dialect, "name")} {text} NOT NULL, {Q(dialect, "email")} {text}, {Q(dialect, "active")} {boolean}, {Q(dialect, "age")} {integer}){terminator}";
        yield return $"CREATE TABLE {Q(dialect, "orders")} ({Q(dialect, "id")} {identity}, {Q(dialect, "user_id")} {integer} NOT NULL, {Q(dialect, "name")} {text} NOT NULL, {Q(dialect, "total")} {integer} NOT NULL){terminator}";

        foreach ( ( string name, string? email, bool active, int age ) in Users )
        {
            yield return $"INSERT INTO {Q(dialect, "users")} ({Q(dialect, "name")}, {Q(dialect, "email")}, {Q(dialect, "active")}, {Q(dialect, "age")}) VALUES ({Literal(name)}, {Literal(email)}, {Boolean(dialect, active)}, {age}){terminator}";
        }

        foreach ( ( int userID, string name, int total ) in Orders )
        {
            yield return $"INSERT INTO {Q(dialect, "orders")} ({Q(dialect, "user_id")}, {Q(dialect, "name")}, {Q(dialect, "total")}) VALUES ({userID}, {Literal(name)}, {total}){terminator}";
        }
    }


    private static readonly (string Name, string? Email, bool Active, int Age)[] Users =
    [
        ( "Ada", "ada@x.io", true, 36 ),
        ( "Bob", null, false, 17 ),
        ( "Cy", "cy@x.io", true, 65 ),
        ( "O'Brien", "ob@x.io", true, 40 )
    ];

    private static readonly (int UserID, string Name, int Total)[] Orders =
    [
        ( 1, "a", 10 ),
        ( 1, "b", 20 ),
        ( 3, "c", 5 ),
        ( 99, "d", 7 )
    ];


    private static (string Identity, string Text, string Integer, string Boolean) Types( SqlDialectKind dialect ) => dialect switch
                                                                                                                     {
                                                                                                                         SqlDialectKind.PostgreSql => ( "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "VARCHAR(100)", "INTEGER", "BOOLEAN" ),
                                                                                                                         SqlDialectKind.SqlServer  => ( "INT IDENTITY(1,1) PRIMARY KEY", "NVARCHAR(100)", "INT", "BIT" ),
                                                                                                                         SqlDialectKind.Sqlite     => ( "INTEGER PRIMARY KEY AUTOINCREMENT", "TEXT", "INTEGER", "INTEGER" ),
                                                                                                                         SqlDialectKind.MySql      => ( "INT AUTO_INCREMENT PRIMARY KEY", "VARCHAR(100)", "INT", "BOOLEAN" ),
                                                                                                                         SqlDialectKind.Oracle     => ( "NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "VARCHAR2(100)", "NUMBER(10)", "NUMBER(1)" ),
                                                                                                                         SqlDialectKind.Firebird   => ( "INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "VARCHAR(100)", "INTEGER", "BOOLEAN" ),
                                                                                                                         _                         => throw new ArgumentOutOfRangeException(nameof(dialect), dialect, null)
                                                                                                                     };

    public static string Q( SqlDialectKind dialect, string name )
    {
        string folded = dialect.Fold(name);
        ( char open, char close ) = dialect.QuoteChars();

        return open is '\0'
                   ? folded
                   : $"{open}{folded}{close}";
    }

    private static string Literal( string? value ) => value is null
                                                          ? "NULL"
                                                          : $"'{value.Replace("'", "''")}'";
    private static string Boolean( SqlDialectKind dialect, bool value ) => dialect.SupportsBooleanLiteral()
                                                                               ? value ? "TRUE" : "FALSE"
                                                                               : value ? "1" : "0";
}
