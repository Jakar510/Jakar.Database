/// <summary> <c>ALTER TABLE name</c>: one action per statement (the portable form). </summary>
public ref struct AlterTableStage
{
    private          SqlWriter __w;
    private readonly string    __table;

    internal AlterTableStage( SqlWriter writer, string table )
    {
        __w     = writer;
        __table = table;
    }

    private void Begin()
    {
        __w.Word("ALTER TABLE");
        __w.Identifier(__table);
    }

    private DdlStage Done() => new(__w);

    /// <summary> <c>ADD [COLUMN] name type ...</c>. </summary>
    public DdlStage AddColumn( string name, SqlType type, SqlColumnDefFn? describe = null ) => AddColumn(name, type.ColumnName(__w.Dialect), describe);
    public DdlStage AddColumn( string name, string typeName, SqlColumnDefFn? describe = null )
    {
        Begin();
        __w.Word(__w.Dialect is SqlDialectKind.PostgreSql or SqlDialectKind.Sqlite or SqlDialectKind.MySql ? "ADD COLUMN" : "ADD");
        SqlColumnDef.Write(ref __w, name, SqlWriter.RequireName(typeName, nameof(typeName)), describe, true);
        return Done();
    }

    /// <summary> <c>DROP COLUMN [IF EXISTS] name</c> (Firebird: <c>DROP name</c>; <c>IF EXISTS</c> on PostgreSQL and SQL Server). </summary>
    public DdlStage DropColumn( string name, bool ifExists = false )
    {
        Begin();
        __w.Word(__w.Dialect is SqlDialectKind.Firebird ? "DROP" : "DROP COLUMN");
        if ( ifExists )
        {
            __w.Require(__w.Dialect is SqlDialectKind.PostgreSql or SqlDialectKind.SqlServer, "DROP COLUMN IF EXISTS");
            __w.Word("IF EXISTS");
        }

        __w.Identifier(name);
        return Done();
    }

    /// <summary> Changes a column's type: <c>ALTER COLUMN c TYPE t</c> / <c>ALTER COLUMN c t</c> / <c>MODIFY COLUMN c t</c> / <c>MODIFY (c t)</c>. </summary>
    public DdlStage AlterColumnType( string name, SqlType type )
    {
        __w.Require(__w.Dialect.SupportsAlterColumnType(), "Changing a column's type");
        string typeName = type.ColumnName(__w.Dialect);
        Begin();

        switch ( __w.Dialect )
        {
            case SqlDialectKind.SqlServer:
                __w.Word("ALTER COLUMN");
                __w.Identifier(name);
                __w.Word(typeName);
                break;

            case SqlDialectKind.MySql:
                __w.Word("MODIFY COLUMN");
                __w.Identifier(name);
                __w.Word(typeName);
                break;

            case SqlDialectKind.Oracle:
                __w.Word("MODIFY");
                __w.OpenParen();
                __w.Identifier(name);
                __w.Word(typeName);
                __w.CloseParen();
                break;

            default:
                __w.Word("ALTER COLUMN");
                __w.Identifier(name);
                __w.Word("TYPE");
                __w.Word(typeName);
                break;
        }

        return Done();
    }

    /// <summary> <c>RENAME COLUMN a TO b</c> (Firebird: <c>ALTER COLUMN a TO b</c>; SQL Server: <c>EXEC sp_rename</c>). </summary>
    public DdlStage RenameColumn( string name, string newName )
    {
        if ( __w.Dialect is SqlDialectKind.SqlServer )
        {
            Ddl.Rename(ref __w, $"{SqlWriter.RequireName(__table)}.{SqlWriter.RequireName(name, nameof(name))}", newName, "COLUMN");
            return Done();
        }

        Begin();
        __w.Word(__w.Dialect is SqlDialectKind.Firebird ? "ALTER COLUMN" : "RENAME COLUMN");
        __w.Identifier(name);
        __w.Word("TO");
        __w.Identifier(newName);
        return Done();
    }

    /// <summary> <c>RENAME TO new</c> (SQL Server: <c>EXEC sp_rename</c>; not Firebird). </summary>
    public DdlStage RenameTo( string newName )
    {
        __w.Require(__w.Dialect.SupportsRenameTable(), "Renaming a table");
        if ( __w.Dialect is SqlDialectKind.SqlServer )
        {
            Ddl.Rename(ref __w, __table, newName, null);
            return Done();
        }

        Begin();
        __w.Word("RENAME TO");
        __w.Identifier(newName);
        return Done();
    }

    public DdlStage AddPrimaryKey( string constraint, params ReadOnlySpan<string> columns )
    {
        AddConstraint(constraint);
        Constraints.PrimaryKey(ref __w, columns);
        return Done();
    }
    public DdlStage AddUnique( string constraint, params ReadOnlySpan<string> columns )
    {
        AddConstraint(constraint);
        Constraints.Unique(ref __w, columns);
        return Done();
    }
    public DdlStage AddForeignKey( string constraint, string[] columns, string table, string[] referenced, SqlReferentialAction onDelete = SqlReferentialAction.NoAction, SqlReferentialAction onUpdate = SqlReferentialAction.NoAction )
    {
        AddConstraint(constraint);
        Constraints.ForeignKey(ref __w, columns, table, referenced, onDelete, onUpdate);
        return Done();
    }
    public DdlStage AddCheck( string constraint, SqlPredicateFn predicate )
    {
        AddConstraint(constraint);
        Constraints.Check(ref __w, predicate);
        return Done();
    }

    public DdlStage DropConstraint( string constraint )
    {
        __w.Require(__w.Dialect.SupportsAlterConstraints(), "ALTER TABLE ... DROP CONSTRAINT");
        Begin();
        __w.Word("DROP CONSTRAINT");
        __w.Identifier(constraint);
        return Done();
    }

    private void AddConstraint( string constraint )
    {
        __w.Require(__w.Dialect.SupportsAlterConstraints(), "ALTER TABLE ... ADD CONSTRAINT");
        Begin();
        __w.Word("ADD CONSTRAINT");
        __w.Identifier(constraint);
    }
}



/// <summary> After <c>CREATE [UNIQUE] INDEX name ON table</c>: optionally <c>USING method</c>, then the key columns. </summary>
public ref struct CreateIndexStage
{
    private SqlWriter __w;

    internal CreateIndexStage( SqlWriter writer ) => __w = writer;

    /// <summary> PostgreSQL's index method: <c>USING gin</c>, <c>gist</c>, <c>brin</c>, <c>hash</c>, ... </summary>
    public CreateIndexStage Using( string method )
    {
        __w.Require(__w.Dialect.SupportsIndexMethod(), "USING (index method)");
        foreach ( char c in SqlWriter.RequireName(method, nameof(method)) )
        {
            if ( !char.IsAsciiLetterOrDigit(c) && c is not '_' ) { throw new ArgumentException($"'{method}' isn't an index method.", nameof(method)); }
        }

        __w.Word("USING");
        __w.Word(method.ToLowerInvariant());
        return new CreateIndexStage(__w);
    }

    public CreateIndexColumnsStage Columns( params ReadOnlySpan<string> columns )
    {
        __w.RequireItems(columns.Length, "CREATE INDEX");
        Clauses.WriteIdentifiers(ref __w, columns);
        return new CreateIndexColumnsStage(__w);
    }

    /// <summary> Key columns with a direction each: <c>.Columns(("created", true), ("id", false))</c> for <c>(created DESC, id)</c>. </summary>
    public CreateIndexColumnsStage Columns( params ReadOnlySpan<(string Column, bool Descending)> columns )
    {
        __w.RequireItems(columns.Length, "CREATE INDEX");
        if ( __w.Dialect is SqlDialectKind.Firebird )
        {
            foreach ( ( string _, bool descending ) in columns ) { __w.Require(!descending, "A descending index key (Firebird orders a whole index: CREATE DESCENDING INDEX)"); }
        }

        __w.OpenParen();
        for ( int i = 0; i < columns.Length; i++ )
        {
            if ( i > 0 ) { __w.Comma(); }

            __w.Identifier(columns[i].Column);
            if ( columns[i].Descending ) { __w.Word("DESC"); }
        }

        __w.CloseParen();
        return new CreateIndexColumnsStage(__w);
    }

    public CreateIndexColumnsStage Columns<T>( params ReadOnlySpan<string> propertyNames )
        where T : ISqlTable<T>
    {
        __w.RequireItems(propertyNames.Length, "CREATE INDEX");
        __w.OpenParen();
        for ( int i = 0; i < propertyNames.Length; i++ )
        {
            if ( i > 0 ) { __w.Comma(); }

            ISqlColumn column = TypedColumns.Resolve<T>(propertyNames[i], in __w);
            __w.PreparedIdentifier(__w.Dialect.Fold(column.GetColumnName(__w.Dialect)));
        }

        __w.CloseParen();
        return new CreateIndexColumnsStage(__w);
    }
}



/// <summary> After the index columns: <c>INCLUDE (...)</c>, a partial-index <c>WHERE</c>, terminate. </summary>
public ref struct CreateIndexColumnsStage
{
    private SqlWriter __w;

    internal CreateIndexColumnsStage( SqlWriter writer ) => __w = writer;

    /// <summary> Covering columns: <c>INCLUDE (a, b)</c> (PostgreSQL, SQL Server). </summary>
    public CreateIndexColumnsStage Include( params ReadOnlySpan<string> columns )
    {
        __w.Require(__w.Dialect.SupportsIndexInclude(), "INCLUDE");
        __w.RequireItems(columns.Length, "INCLUDE");
        __w.Word("INCLUDE");
        Clauses.WriteIdentifiers(ref __w, columns);
        return new CreateIndexColumnsStage(__w);
    }

    /// <summary> A partial (filtered) index: <c>WHERE predicate</c> (PostgreSQL, SQLite, SQL Server). </summary>
    public DdlStage Where( SqlPredicateFn predicate )
    {
        __w.Require(__w.Dialect.SupportsPartialIndex(), "A partial index (CREATE INDEX ... WHERE)");
        __w.Word("WHERE");
        Predicates.Write(ref __w, predicate);
        return new DdlStage(__w);
    }

    public SqlResult       Build()                                  => __w.Build();
    public string          BuildSql()                               => __w.BuildSql();
    public SqlParameterSet WriteTo( IBufferWriter<char> destination ) => __w.WriteTo(destination);
}



/// <summary> Table constraints and the column definitions written from metadata. </summary>
internal static class Constraints
{
    public static void PrimaryKey( scoped ref SqlWriter writer, scoped ReadOnlySpan<string> columns )
    {
        writer.RequireItems(columns.Length, "PRIMARY KEY");
        writer.Word("PRIMARY KEY");
        Clauses.WriteIdentifiers(ref writer, columns);
    }

    public static void Unique( scoped ref SqlWriter writer, scoped ReadOnlySpan<string> columns )
    {
        writer.RequireItems(columns.Length, "UNIQUE");
        writer.Word("UNIQUE");
        Clauses.WriteIdentifiers(ref writer, columns);
    }

    public static void ForeignKey( scoped ref SqlWriter writer, string[] columns, string table, string[] referenced, SqlReferentialAction onDelete, SqlReferentialAction onUpdate )
    {
        ArgumentNullException.ThrowIfNull(columns);
        ArgumentNullException.ThrowIfNull(referenced);
        writer.RequireItems(columns.Length, "FOREIGN KEY");
        if ( referenced.Length != columns.Length ) { throw new ArgumentException($"The foreign key has {columns.Length} column(s) but references {referenced.Length}.", nameof(referenced)); }

        writer.Word("FOREIGN KEY");
        Clauses.WriteIdentifiers(ref writer, columns);
        writer.Word("REFERENCES");
        writer.Identifier(table);
        Clauses.WriteIdentifiers(ref writer, referenced);
        Actions(ref writer, onDelete, onUpdate);
    }

    public static void Check( scoped ref SqlWriter writer, SqlPredicateFn predicate )
    {
        writer.Word("CHECK");
        writer.OpenParen();
        Predicates.Write(ref writer, predicate);
        writer.CloseParen();
    }

    public static void Actions( scoped ref SqlWriter writer, SqlReferentialAction onDelete, SqlReferentialAction onUpdate )
    {
        if ( onDelete is not SqlReferentialAction.NoAction )
        {
            Validate(in writer, onDelete, "ON DELETE");
            writer.Word("ON DELETE");
            writer.Word(Keyword(onDelete));
        }

        if ( onUpdate is not SqlReferentialAction.NoAction )
        {
            writer.Require(writer.Dialect is not SqlDialectKind.Oracle, "ON UPDATE");
            Validate(in writer, onUpdate, "ON UPDATE");
            writer.Word("ON UPDATE");
            writer.Word(Keyword(onUpdate));
        }
    }

    private static void Validate( scoped in SqlWriter writer, SqlReferentialAction action, string clause )
    {
        switch ( action )
        {
            case SqlReferentialAction.Restrict:
                writer.Require(writer.Dialect is not SqlDialectKind.SqlServer and not SqlDialectKind.Oracle and not SqlDialectKind.Firebird, $"{clause} RESTRICT");
                break;

            case SqlReferentialAction.SetDefault:
                writer.Require(writer.Dialect is not SqlDialectKind.Oracle and not SqlDialectKind.MySql, $"{clause} SET DEFAULT");
                break;
        }
    }

    private static string Keyword( SqlReferentialAction action ) => action switch
                                                                    {
                                                                        SqlReferentialAction.Cascade    => "CASCADE",
                                                                        SqlReferentialAction.SetNull    => "SET NULL",
                                                                        SqlReferentialAction.SetDefault => "SET DEFAULT",
                                                                        SqlReferentialAction.Restrict   => "RESTRICT",
                                                                        _                               => "NO ACTION"
                                                                    };

    /// <summary> One column of <c>CREATE TABLE</c> from metadata. The type, default and check are the metadata's own (trusted) SQL. </summary>
    public static void MetadataColumn( scoped ref SqlWriter writer, ISqlColumn column, bool singleKey )
    {
        SqlDialectKind dialect  = writer.Dialect;
        string         typeName = column.GetTypeName(dialect);
        bool           identity = column.IsIdentity;
        if ( string.IsNullOrWhiteSpace(typeName) ) { throw writer.Error(SqlBuildError.UnsupportedFeature, $"'{column.PropertyName}' has no {dialect} type in its metadata."); }

        // PostgreSQL's SERIAL types are already auto-numbered.
        if ( identity && dialect is SqlDialectKind.PostgreSql && typeName.EndsWith("SERIAL", StringComparison.OrdinalIgnoreCase) ) { identity = false; }

        writer.PreparedIdentifier(dialect.Fold(column.GetColumnName(dialect)));
        writer.Word(identity && dialect is SqlDialectKind.Sqlite
                        ? "INTEGER"
                        : typeName);

        if ( identity && dialect is not SqlDialectKind.MySql and not SqlDialectKind.Sqlite )
        {
            writer.Word(dialect is SqlDialectKind.SqlServer
                            ? "IDENTITY(1,1)"
                            : column.IsAlwaysIdentity
                                ? "GENERATED ALWAYS AS IDENTITY"
                                : "GENERATED BY DEFAULT AS IDENTITY");
        }

        if ( !identity && column.GetDefaultSql(dialect) is { Length: > 0 } defaultSql )
        {
            writer.Word("DEFAULT");
            writer.InlineRaw(defaultSql);
        }

        if ( !column.IsNullable ) { writer.Word("NOT NULL"); }

        if ( identity && dialect is SqlDialectKind.MySql ) { writer.Word("AUTO_INCREMENT"); }

        if ( identity && dialect is SqlDialectKind.Sqlite ) { writer.Word("PRIMARY KEY AUTOINCREMENT"); }
        else if ( column.IsPrimaryKey && singleKey ) { writer.Word("PRIMARY KEY"); }

        if ( column.IsUnique && !column.IsPrimaryKey ) { writer.Word("UNIQUE"); }

        if ( column.GetCheckSql(dialect) is { Length: > 0 } check )
        {
            writer.Word("CHECK");
            writer.OpenParen();
            writer.InlineRaw(check);
            writer.CloseParen();
        }

        if ( column.ForeignTable is { Length: > 0 } foreignTable ) { References(ref writer, column.GetColumnName(dialect), foreignTable, column.ForeignColumn ?? "id", column.OnDelete, column.OnUpdate, false); }
    }

    /// <summary> A column's <c>REFERENCES table (column)</c>. MySQL parses but ignores that inline form, so it gets <c>, FOREIGN KEY (column) REFERENCES ...</c> right after the column. </summary>
    public static void References( scoped ref SqlWriter writer, string column, string table, string referenced, SqlReferentialAction onDelete, SqlReferentialAction onUpdate, bool alter )
    {
        if ( writer.Dialect is SqlDialectKind.MySql )
        {
            writer.Comma();
            if ( alter ) { writer.Word("ADD"); }

            writer.Word("FOREIGN KEY");
            writer.OpenParen();
            writer.Identifier(column);
            writer.CloseParen();
        }

        writer.Word("REFERENCES");
        writer.Identifier(table);
        writer.OpenParen();
        writer.Identifier(referenced);
        writer.CloseParen();
        Actions(ref writer, onDelete, onUpdate);
    }
}



internal static class Ddl
{
    public static SqlWriter Start( SqlWriter writer )
    {
        if ( writer.Has(ClauseFlags.With) ) { throw writer.Error(SqlBuildError.UnsupportedFeature, "DDL can't follow WITH."); }

        writer.MarkClause(ClauseFlags.Ddl);
        return writer;
    }

    public static CreateTableStage CreateTable( scoped ref SqlWriter writer, string name, bool ifNotExists )
    {
        writer = Start(writer);
        if ( ifNotExists && writer.Dialect is SqlDialectKind.SqlServer )
        {
            writer.Word("IF OBJECT_ID");
            writer.OpenCall();
            writer.InlineString(SqlWriter.RequireName(name, nameof(name)));
            writer.Comma();
            writer.InlineString("U");
            writer.CloseParen();
            writer.Word("IS NULL");
            ifNotExists = false;
        }

        writer.Word("CREATE TABLE");
        if ( ifNotExists )
        {
            writer.Require(writer.Dialect.SupportsCreateIfNotExists(), "CREATE TABLE IF NOT EXISTS");
            writer.Word("IF NOT EXISTS");
        }

        writer.Identifier(name);
        writer.OpenParen();
        return new CreateTableStage(writer, false);
    }

    public static DdlStage Drop( scoped ref SqlWriter writer, string kind, string name, bool ifExists, bool cascade )
    {
        writer = Start(writer);
        writer.Word("DROP");
        writer.Word(kind);
        if ( ifExists )
        {
            writer.Require(writer.Dialect.SupportsDropIfExists(), $"DROP {kind} IF EXISTS");
            writer.Word("IF EXISTS");
        }

        writer.Identifier(name);
        if ( cascade )
        {
            writer.Require(writer.Dialect.SupportsDropCascade(), $"DROP {kind} ... CASCADE");
            writer.Word(writer.Dialect is SqlDialectKind.Oracle ? "CASCADE CONSTRAINTS" : "CASCADE");
        }

        return new DdlStage(writer);
    }

    public static DdlStage DropIndex( scoped ref SqlWriter writer, string name, string? table, bool ifExists )
    {
        writer = Start(writer);
        bool needsTable = writer.Dialect is SqlDialectKind.SqlServer or SqlDialectKind.MySql;
        if ( needsTable && table is not { Length: > 0 } ) { throw new ArgumentException($"{writer.Dialect} drops an index ON its table; pass the table.", nameof(table)); }

        writer.Word("DROP INDEX");
        if ( ifExists )
        {
            writer.Require(writer.Dialect.SupportsDropIfExists() && writer.Dialect is not SqlDialectKind.MySql, "DROP INDEX IF EXISTS");
            writer.Word("IF EXISTS");
        }

        writer.Identifier(name);
        if ( needsTable )
        {
            writer.Word("ON");
            writer.Identifier(table!);
        }

        return new DdlStage(writer);
    }

    public static CreateIndexStage CreateIndex( scoped ref SqlWriter writer, string name, string table, bool unique, bool ifNotExists )
    {
        writer = Start(writer);
        if ( ifNotExists && writer.Dialect is SqlDialectKind.SqlServer )
        {
            // SQL Server has no CREATE INDEX IF NOT EXISTS: guard it.
            writer.Word("IF NOT EXISTS");
            writer.OpenParen();
            writer.Word("SELECT 1 FROM sys.indexes WHERE name =");
            writer.InlineString(SqlWriter.RequireName(name, nameof(name)));
            writer.Word("AND object_id = OBJECT_ID");
            writer.OpenCall();
            writer.InlineString(SqlWriter.RequireName(table, nameof(table)));
            writer.CloseParen();
            writer.CloseParen();
            ifNotExists = false;
        }

        writer.Word(unique ? "CREATE UNIQUE INDEX" : "CREATE INDEX");
        if ( ifNotExists )
        {
            writer.Require(writer.Dialect.SupportsIndexIfNotExists(), "CREATE INDEX IF NOT EXISTS");
            writer.Word("IF NOT EXISTS");
        }

        writer.Identifier(name);
        writer.Word("ON");
        writer.Identifier(table);
        return new CreateIndexStage(writer);
    }

    public static DdlStage CreateView<TEnd>( scoped ref SqlWriter writer, string name, SqlSubquery<TEnd> query, scoped ReadOnlySpan<string> columns, bool orReplace )
        where TEnd : ISqlQueryEnd, allows ref struct
    {
        writer = Start(writer);
        if ( orReplace )
        {
            writer.Require(writer.Dialect.SupportsReplaceView(), "CREATE OR REPLACE VIEW");
            writer.Word(writer.Dialect is SqlDialectKind.SqlServer or SqlDialectKind.Firebird ? "CREATE OR ALTER VIEW" : "CREATE OR REPLACE VIEW");
        }
        else { writer.Word("CREATE VIEW"); }

        writer.Identifier(name);
        if ( columns.Length > 0 ) { Clauses.WriteIdentifiers(ref writer, columns); }

        writer.Word("AS");
        Subqueries.Write(ref writer, query, false);
        return new DdlStage(writer);
    }

    /// <summary> SQL Server's <c>EXEC sp_rename N'old', N'new'[, N'kind']</c>. </summary>
    public static void Rename( scoped ref SqlWriter writer, string current, string newName, string? kind )
    {
        writer.Word("EXEC sp_rename");
        writer.InlineString(current);
        writer.Comma();
        writer.InlineString(SqlWriter.RequireName(newName, nameof(newName)));
        if ( kind is null ) { return; }

        writer.Comma();
        writer.InlineString(kind);
    }
}
