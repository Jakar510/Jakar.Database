namespace Jakar.SqlBuilder;


/// <summary> What a foreign key does when the referenced row is deleted or updated. </summary>
public enum SqlReferentialAction : byte
{
    NoAction,
    Cascade,
    SetNull,
    SetDefault,
    Restrict
}



/// <summary> A finished DDL statement. </summary>
public ref struct DdlStage
{
    private SqlWriter __w;

    internal DdlStage( SqlWriter writer ) => __w = writer;

    public SqlResult       Build()                                  => __w.Build();
    public string          BuildSql()                               => __w.BuildSql();
    public SqlParameterSet WriteTo( IBufferWriter<char> destination ) => __w.WriteTo(destination);
}



/// <summary> Describes one column of <c>CREATE TABLE</c> / <c>ADD COLUMN</c>: <c>c =&gt; c.NotNull().Default(SqlValue.Of(0))</c>. </summary>
public delegate SqlColumnDef SqlColumnDefFn( SqlColumnDef column );



/// <summary> The constraints of one column. Written in the order every dialect accepts: identity, <c>DEFAULT</c>, nullability, keys, <c>CHECK</c>, <c>REFERENCES</c>. </summary>
public readonly struct SqlColumnDef
{
    private readonly ColumnOptions        __options;
    private readonly SqlValue             __default;
    private readonly SqlExprFn?           __defaultExpression;
    private readonly SqlPredicateFn?      __check;
    private readonly string?              __referencesTable;
    private readonly string?              __referencesColumn;
    private readonly SqlReferentialAction __onDelete;
    private readonly SqlReferentialAction __onUpdate;

    private SqlColumnDef( ColumnOptions options, SqlValue @default, SqlExprFn? defaultExpression, SqlPredicateFn? check, string? referencesTable, string? referencesColumn, SqlReferentialAction onDelete, SqlReferentialAction onUpdate )
    {
        __options           = options;
        __default           = @default;
        __defaultExpression = defaultExpression;
        __check             = check;
        __referencesTable   = referencesTable;
        __referencesColumn  = referencesColumn;
        __onDelete          = onDelete;
        __onUpdate          = onUpdate;
    }

    private SqlColumnDef With( ColumnOptions add ) => new(__options | add, __default, __defaultExpression, __check, __referencesTable, __referencesColumn, __onDelete, __onUpdate);

    public SqlColumnDef NotNull()    => With(ColumnOptions.NotNull);
    public SqlColumnDef Nullable()   => With(ColumnOptions.Nullable);
    public SqlColumnDef PrimaryKey() => With(ColumnOptions.PrimaryKey);
    public SqlColumnDef Unique()     => With(ColumnOptions.Unique);

    /// <summary>
    ///     An auto-numbered column: <c>GENERATED BY DEFAULT AS IDENTITY</c> (or <c>ALWAYS</c>), <c>IDENTITY(1,1)</c> (SQL Server), <c>AUTO_INCREMENT</c> (MySQL), or
    ///     <c>INTEGER PRIMARY KEY AUTOINCREMENT</c> (SQLite, which makes it the primary key).
    /// </summary>
    public SqlColumnDef Identity( bool always = false ) => With(always
                                                                    ? ColumnOptions.Identity | ColumnOptions.Always
                                                                    : ColumnOptions.Identity);

    /// <summary> <c>DEFAULT value</c> (an inline value: DDL can't bind parameters). </summary>
    public SqlColumnDef Default( SqlValue value ) => new(__options | ColumnOptions.Default, value, null, __check, __referencesTable, __referencesColumn, __onDelete, __onUpdate);

    /// <summary> <c>DEFAULT expression</c>, e.g. <c>e =&gt; e.CurrentTimestamp()</c> (MySQL: <c>DEFAULT (expression)</c>). </summary>
    public SqlColumnDef Default( SqlExprFn expression ) => new(__options | ColumnOptions.Default, default, expression ?? throw new ArgumentNullException(nameof(expression)), __check, __referencesTable, __referencesColumn, __onDelete, __onUpdate);

    public SqlColumnDef Check( SqlPredicateFn predicate ) => new(__options, __default, __defaultExpression, predicate ?? throw new ArgumentNullException(nameof(predicate)), __referencesTable, __referencesColumn, __onDelete, __onUpdate);

    /// <summary> <c>REFERENCES table (column) [ON DELETE ...] [ON UPDATE ...]</c>. </summary>
    public SqlColumnDef References( string table, string column, SqlReferentialAction onDelete = SqlReferentialAction.NoAction, SqlReferentialAction onUpdate = SqlReferentialAction.NoAction ) =>
        new(__options, __default, __defaultExpression, __check, SqlWriter.RequireName(table, nameof(table)), SqlWriter.RequireName(column, nameof(column)), onDelete, onUpdate);

    internal bool IsIdentity => ( __options & ColumnOptions.Identity ) != 0;

    /// <param name="alter"> The column is added by <c>ALTER TABLE</c> (MySQL's separate foreign key clause then needs its own <c>ADD</c>). </param>
    internal static void Write( scoped ref SqlWriter writer, string name, string typeName, SqlColumnDefFn? describe, bool alter = false )
    {
        SqlColumnDef def = describe?.Invoke(default) ?? default;
        def.Write(ref writer, name, typeName, alter);
    }

    internal void Write( scoped ref SqlWriter writer, string name, string typeName, bool alter )
    {
        SqlDialectKind dialect  = writer.Dialect;
        bool           identity = ( __options & ColumnOptions.Identity ) != 0;
        bool           primary  = ( __options & ColumnOptions.PrimaryKey ) != 0;

        if ( identity && ( __options & ColumnOptions.Default ) != 0 ) { throw new ArgumentException($"Column '{name}' can't be an identity and have a DEFAULT.", nameof(name)); }

        if ( ( __options & ColumnOptions.NotNull ) != 0 && ( __options & ColumnOptions.Nullable ) != 0 ) { throw new ArgumentException($"Column '{name}' can't be both NULL and NOT NULL.", nameof(name)); }

        writer.Identifier(name);
        writer.Word(identity && dialect is SqlDialectKind.Sqlite
                        ? "INTEGER"
                        : typeName);

        if ( identity && dialect is not SqlDialectKind.MySql and not SqlDialectKind.Sqlite )
        {
            writer.Word(dialect is SqlDialectKind.SqlServer
                            ? "IDENTITY(1,1)"
                            : ( __options & ColumnOptions.Always ) != 0
                                ? "GENERATED ALWAYS AS IDENTITY"
                                : "GENERATED BY DEFAULT AS IDENTITY");
        }

        if ( ( __options & ColumnOptions.Default ) != 0 )
        {
            writer.Word("DEFAULT");
            if ( __defaultExpression is not null )
            {
                if ( dialect is SqlDialectKind.MySql ) { writer.OpenParen(); }

                SqlExpr.Write(ref writer, __defaultExpression);
                if ( dialect is SqlDialectKind.MySql ) { writer.CloseParen(); }
            }
            else { __default.Write(ref writer); }
        }

        if ( ( __options & ColumnOptions.NotNull ) != 0 ) { writer.Word("NOT NULL"); }
        else if ( ( __options & ColumnOptions.Nullable ) != 0 && dialect is not SqlDialectKind.Firebird ) { writer.Word("NULL"); }

        if ( identity && dialect is SqlDialectKind.MySql ) { writer.Word("AUTO_INCREMENT"); }

        if ( identity && dialect is SqlDialectKind.Sqlite ) { writer.Word("PRIMARY KEY AUTOINCREMENT"); }
        else if ( primary ) { writer.Word("PRIMARY KEY"); }

        if ( ( __options & ColumnOptions.Unique ) != 0 ) { writer.Word("UNIQUE"); }

        if ( __check is not null )
        {
            writer.Word("CHECK");
            writer.OpenParen();
            Predicates.Write(ref writer, __check);
            writer.CloseParen();
        }

        if ( __referencesTable is not null ) { Constraints.References(ref writer, name, __referencesTable, __referencesColumn!, __onDelete, __onUpdate, alter); }
    }



    [Flags]
    private enum ColumnOptions : byte
    {
        None       = 0,
        NotNull    = 1 << 0,
        Nullable   = 1 << 1,
        PrimaryKey = 1 << 2,
        Unique     = 1 << 3,
        Identity   = 1 << 4,
        Always     = 1 << 5,
        Default    = 1 << 6
    }
}



/// <summary> Inside <c>CREATE TABLE name (</c>: columns, then table constraints, then build (which closes the list). </summary>
public ref struct CreateTableStage
{
    private SqlWriter __w;
    private bool      __has;

    internal CreateTableStage( SqlWriter writer, bool has )
    {
        __w   = writer;
        __has = has;
    }

    private void Next()
    {
        if ( __has ) { __w.Comma(); }
    }

    /// <summary> A column with a portable type: <c>.Column("id", SqlType.BigInt, c =&gt; c.Identity().PrimaryKey())</c>. </summary>
    public CreateTableStage Column( string name, SqlType type, SqlColumnDefFn? describe = null )
    {
        Next();
        SqlColumnDef.Write(ref __w, name, type.ColumnName(__w.Dialect), describe);
        return new CreateTableStage(__w, true);
    }

    /// <summary> A column with a dialect-specific type name (trusted, written as is), e.g. <c>"JSONB"</c>. </summary>
    public CreateTableStage Column( string name, string typeName, SqlColumnDefFn? describe = null )
    {
        Next();
        SqlColumnDef.Write(ref __w, name, SqlWriter.RequireName(typeName, nameof(typeName)), describe);
        return new CreateTableStage(__w, true);
    }

    /// <summary> Every mapped column of <typeparamref name="T"/>, from its metadata (see <see cref="SqlRoot.CreateTable{T}"/>). </summary>
    internal CreateTableStage Columns<T>()
        where T : ISqlTable<T>
    {
        IReadOnlyList<ISqlColumn> columns = T.SqlColumns;
        if ( columns.Count is 0 ) { throw __w.Error(SqlBuildError.MissingRequiredClause, $"{T.SqlTableName} has no mapped columns."); }

        IReadOnlyList<string> tableKey = T.SqlPrimaryKey;
        int                   keys     = 0;
        foreach ( ISqlColumn column in columns )
        {
            if ( column.IsPrimaryKey ) { keys++; }
        }

        if ( tableKey.Count > 0 ) { keys = 0; } // the table's own key replaces the columns' flags

        foreach ( ISqlColumn column in columns )
        {
            Next();
            Constraints.MetadataColumn(ref __w, column, keys is 1);
            __has = true;
        }

        if ( keys > 1 )
        {
            __w.Comma();
            __w.Word("PRIMARY KEY");
            __w.OpenParen();
            bool first = true;
            foreach ( ISqlColumn column in columns )
            {
                if ( !column.IsPrimaryKey ) { continue; }

                if ( !first ) { __w.Comma(); }

                __w.PreparedIdentifier(__w.Dialect.Fold(column.GetColumnName(__w.Dialect)));
                first = false;
            }

            __w.CloseParen();
        }

        if ( tableKey.Count > 0 ) { TableKey(ref __w, "PRIMARY KEY", tableKey); }

        foreach ( IReadOnlyList<string> unique in T.SqlUniqueKeys ) { TableKey(ref __w, "UNIQUE", unique); }

        return new CreateTableStage(__w, true);
    }

    private static void TableKey( scoped ref SqlWriter writer, string keyword, IReadOnlyList<string> columns )
    {
        writer.Comma();
        writer.Word(keyword);
        writer.OpenParen();
        for ( int i = 0; i < columns.Count; i++ )
        {
            if ( i > 0 ) { writer.Comma(); }

            writer.Identifier(columns[i]);
        }

        writer.CloseParen();
    }

    public CreateTableStage PrimaryKey( params ReadOnlySpan<string> columns )
    {
        RequireColumns();
        __w.Comma();
        Constraints.PrimaryKey(ref __w, columns);
        return new CreateTableStage(__w, true);
    }
    public CreateTableStage Unique( params ReadOnlySpan<string> columns )
    {
        RequireColumns();
        __w.Comma();
        Constraints.Unique(ref __w, columns);
        return new CreateTableStage(__w, true);
    }
    public CreateTableStage ForeignKey( string[] columns, string table, string[] referenced, SqlReferentialAction onDelete = SqlReferentialAction.NoAction, SqlReferentialAction onUpdate = SqlReferentialAction.NoAction )
    {
        RequireColumns();
        __w.Comma();
        Constraints.ForeignKey(ref __w, columns, table, referenced, onDelete, onUpdate);
        return new CreateTableStage(__w, true);
    }
    public CreateTableStage Check( SqlPredicateFn predicate )
    {
        RequireColumns();
        __w.Comma();
        Constraints.Check(ref __w, predicate);
        return new CreateTableStage(__w, true);
    }

    /// <summary> <c>CONSTRAINT name ...</c>: names the next table constraint. </summary>
    public NamedConstraintStage Constraint( string name )
    {
        RequireColumns();
        __w.Comma();
        __w.Word("CONSTRAINT");
        __w.Identifier(name);
        return new NamedConstraintStage(__w);
    }

    private readonly void RequireColumns()
    {
        if ( !__has ) { throw __w.Error(SqlBuildError.MissingRequiredClause, "CREATE TABLE needs a column before its constraints."); }
    }

    private void Close()
    {
        if ( __w.IsBuilt ) { return; }

        RequireColumns();
        __w.CloseParen();
    }

    public SqlResult Build()
    {
        Close();
        return __w.Build();
    }
    public string BuildSql()
    {
        Close();
        return __w.BuildSql();
    }
    public SqlParameterSet WriteTo( IBufferWriter<char> destination )
    {
        Close();
        return __w.WriteTo(destination);
    }
}



